"""EX7: meta-learning across the task stream (Reptile). Does a meta-learned init adapt to a HELD-OUT
task faster than a random-init control at the SAME total optimization budget, or does the task family
generated by make_task_stream just not have enough shared structure for a first-order meta-learner to
exploit on a frozen pooled latent shell this small.

Mechanism: outer-loop Reptile over a stream of meta-train tasks. Each meta-iteration clones the current
shell params, takes k inner SGD steps on a freshly sampled meta-train task, then moves the meta
parameters a small step toward the adapted parameters (theta <- theta + eps * (theta_adapted - theta)).
No second-order gradients, no held-out tasks touched during meta-training.

Evaluation on tasks NEVER seen during meta-training: adaptation_speed counts inner gradient steps from
the meta-init (vs a random-init control, matched total step budget) needed to cross a target accuracy;
forward_transfer is held-out accuracy after a small fixed adaptation budget, meta-init vs random-init.

NULL: the meta-learned init does not reduce adaptation steps vs a control init; the task family is too
homogeneous or the shell too small. Negative-result taxonomy slot 5 (a synthetic Gaussian-cluster task
family shares only coarse geometry across tasks, so a linear/shallow head may find little to transfer)
or slot 4 (predictor too small to encode reusable structure). cpu-now, seconds.

Standing controls: random-init (the adaptation-speed/forward-transfer control proper), hypernet-style
meta-init (a second meta-learned arm from a fixed random seed distinct from the SGD Reptile trace, so
the comparison is not just "trained vs untrained"), matched-budget (adaptation_speed is only meaningful
when both arms get the identical total inner-step budget, enforced directly by the loop below).

Form per BLACKHOLE.md: no em dashes or en dashes (commas, colons, parentheses only).
"""

from __future__ import annotations

import copy
from pathlib import Path

import torch
import torch.nn.functional as F
from omegaconf import DictConfig
from torch import nn

from ..devices import DeviceInfo
from ..diagnostics.compute import param_count
from ..seeding import seed_everything
from ..shell.predictor import mlp
from .base import Experiment


def _head_net(dim: int, hidden: int, n_classes: int) -> nn.Module:
    """The tiny trainable shell that gets meta-learned: a one-hidden-layer classifier over the frozen
    latent. Small on purpose (toy scale), matches the other roots experiments' shell sizes."""
    return mlp(dim, n_classes, hidden, depth=1, ln=True)


def _clone(net: nn.Module) -> nn.Module:
    return copy.deepcopy(net)


def _sgd_steps(net: nn.Module, x, y, steps: int, lr: float) -> nn.Module:
    """Adapt `net` in place for `steps` plain SGD steps on (x, y). Returns the same module."""
    opt = torch.optim.SGD(net.parameters(), lr=lr)
    for _ in range(steps):
        opt.zero_grad()
        F.cross_entropy(net(x), y).backward()
        opt.step()
    return net


def _accuracy(net: nn.Module, x, y) -> float:
    with torch.no_grad():
        return float((net(x).argmax(-1) == y).float().mean())


def _reptile_meta_train(
    init: nn.Module,
    tasks: list,
    inner_steps: int,
    inner_lr: float,
    outer_lr: float,
    meta_iters: int,
    g: torch.Generator,
) -> nn.Module:
    """Standard Reptile outer loop: for each meta-iteration, sample a meta-train task, clone the
    current meta-params, take `inner_steps` SGD steps on that task, then move the meta-params a
    fraction `outer_lr` of the way toward the adapted params. First-order, no held-out task touched."""
    meta = _clone(init)
    n = len(tasks)
    for _ in range(meta_iters):
        idx = int(torch.randint(0, n, (1,), generator=g).item())
        task = tasks[idx]
        adapted = _clone(meta)
        _sgd_steps(adapted, task.x, task.y, inner_steps, inner_lr)
        with torch.no_grad():
            for p_meta, p_adapt in zip(meta.parameters(), adapted.parameters(), strict=True):
                p_meta.add_(outer_lr * (p_adapt.detach() - p_meta))
    return meta


def _steps_to_target(
    init: nn.Module, task, target_acc: float, max_steps: int, lr: float
) -> tuple[int, float]:
    """Adapt a clone of `init` on `task` one SGD step at a time (matched-budget: identical `max_steps`
    ceiling for every arm), returning the first step count that reaches `target_acc` on `task` itself
    (a cheap adaptation-speed proxy, no separate query set needed at this toy scale) and the final
    accuracy reached. If the target is never crossed, returns max_steps (adaptation did not finish
    within budget) and the best accuracy seen."""
    net = _clone(init)
    opt = torch.optim.SGD(net.parameters(), lr=lr)
    best = _accuracy(net, task.x, task.y)
    for step in range(1, max_steps + 1):
        opt.zero_grad()
        F.cross_entropy(net(task.x), task.y).backward()
        opt.step()
        acc = _accuracy(net, task.x, task.y)
        best = max(best, acc)
        if acc >= target_acc:
            return step, acc
    return max_steps, best


def _fixed_budget_accuracy(init: nn.Module, task, adapt_steps: int, lr: float) -> float:
    net = _clone(init)
    _sgd_steps(net, task.x, task.y, adapt_steps, lr)
    return _accuracy(net, task.x, task.y)


class EX7(Experiment):
    id = "ex7_meta_learning"
    metric = (
        "adaptation_speed_meta",
        "adaptation_speed_random",
        "adaptation_speed_gain",
        "forward_transfer_meta",
        "forward_transfer_random",
        "forward_transfer_gain",
    )
    baseline = "random-init control adapted at matched total inner-step budget"
    ablation = (
        "Reptile meta-init vs random-init vs a second fixed-seed (hypernet-style) init, held-out tasks only"
    )
    null_hypothesis = (
        "the meta-learned init does not reduce adaptation steps vs a control init; the task family is "
        "too homogeneous or the shell too small"
    )
    tier = "cpu-now"

    def run(self, cfg: DictConfig, device: DeviceInfo, run_dir: Path) -> dict:
        from ..substrate.datasets import make_task_stream

        e = cfg.experiment
        seeds = list(e.seeds)
        dim, hidden = int(e.dim), int(e.hidden)
        n_classes = int(e.n_classes)
        n_meta_tasks, n_holdout_tasks = int(e.n_meta_tasks), int(e.n_holdout_tasks)
        samples, separation = int(e.samples_per_task), float(e.separation)
        inner_steps, inner_lr = int(e.inner_steps), float(e.inner_lr)
        outer_lr, meta_iters = float(e.outer_lr), int(e.meta_iters)
        target_acc = float(e.target_acc)
        max_adapt_steps = int(e.max_adapt_steps)
        fixed_budget = int(e.fixed_budget_steps)
        margin = float(e.margin)

        speed_meta, speed_rand, speed_hyper = [], [], []
        xfer_meta, xfer_rand, xfer_hyper = [], [], []

        for s in seeds:
            seed_everything(s)
            g = torch.Generator().manual_seed(s)

            # meta-train tasks and held-out tasks are DISJOINT task pools (independent draws,
            # different seeds folded in), so held-out evaluation never leaks into meta-training.
            meta_tasks = make_task_stream(
                n_tasks=n_meta_tasks,
                dim=dim,
                classes_per_task=n_classes,
                samples_per_task=samples,
                separation=separation,
                incremental="task",
                seed=s * 1000 + 1,
            )
            holdout_tasks = make_task_stream(
                n_tasks=n_holdout_tasks,
                dim=dim,
                classes_per_task=n_classes,
                samples_per_task=samples,
                separation=separation,
                incremental="task",
                seed=s * 1000 + 2,
            )

            seed_everything(s)
            random_init = _head_net(dim, hidden, n_classes)

            seed_everything(s)
            meta_start = _head_net(dim, hidden, n_classes)
            meta_init = _reptile_meta_train(
                meta_start, meta_tasks, inner_steps, inner_lr, outer_lr, meta_iters, g
            )

            # hypernet-style control: a SECOND fixed-seed init, distinct from the Reptile trace and
            # from the random-init control's own seed, so a meta-init win cannot be explained away as
            # "any nonzero init beats an unlucky random draw" (matched-budget, standing control).
            seed_everything(s + 777)
            hyper_init = _head_net(dim, hidden, n_classes)

            for task in holdout_tasks:
                sm, _ = _steps_to_target(meta_init, task, target_acc, max_adapt_steps, inner_lr)
                sr, _ = _steps_to_target(random_init, task, target_acc, max_adapt_steps, inner_lr)
                sh, _ = _steps_to_target(hyper_init, task, target_acc, max_adapt_steps, inner_lr)
                speed_meta.append(sm)
                speed_rand.append(sr)
                speed_hyper.append(sh)

                xfer_meta.append(_fixed_budget_accuracy(meta_init, task, fixed_budget, inner_lr))
                xfer_rand.append(_fixed_budget_accuracy(random_init, task, fixed_budget, inner_lr))
                xfer_hyper.append(_fixed_budget_accuracy(hyper_init, task, fixed_budget, inner_lr))

        def _mean(v: list[float] | list[int]) -> float:
            return sum(v) / len(v) if v else 0.0

        def _spread(v: list[float] | list[int]) -> float:
            return (max(v) - min(v)) / 2.0 if len(v) > 1 else 0.0

        speed_meta_mean, speed_rand_mean, speed_hyper_mean = (
            _mean(speed_meta),
            _mean(speed_rand),
            _mean(speed_hyper),
        )
        xfer_meta_mean, xfer_rand_mean, xfer_hyper_mean = (
            _mean(xfer_meta),
            _mean(xfer_rand),
            _mean(xfer_hyper),
        )

        # fewer steps is better for adaptation_speed, so the gain is control-minus-meta
        speed_gain = speed_rand_mean - speed_meta_mean
        xfer_gain = xfer_meta_mean - xfer_rand_mean
        speed_gain_spread = max(_spread(speed_meta), _spread(speed_rand))
        xfer_gain_spread = max(_spread(xfer_meta), _spread(xfer_rand))

        meta_probe = _head_net(dim, hidden, n_classes)
        out = {
            "adaptation_speed_meta": round(speed_meta_mean, 3),
            "adaptation_speed_random": round(speed_rand_mean, 3),
            "adaptation_speed_hypernet": round(speed_hyper_mean, 3),
            "adaptation_speed_gain": round(speed_gain, 3),
            "forward_transfer_meta": round(xfer_meta_mean, 4),
            "forward_transfer_random": round(xfer_rand_mean, 4),
            "forward_transfer_hypernet": round(xfer_hyper_mean, 4),
            "forward_transfer_gain": round(xfer_gain, 4),
            "margin_steps": margin,
            "speed_gain_spread": round(speed_gain_spread, 3),
            "xfer_gain_spread": round(xfer_gain_spread, 4),
            "params": param_count(meta_probe),
            "n_holdout_tasks_total": len(speed_meta),
            "seeds": list(seeds),
            # the explicit null: meta-init does not beat random-init on adaptation speed beyond the
            # matched-budget seed-spread band (a real, honest gain must clear both a fixed step margin
            # and the observed seed-to-seed noise, or the toy task family just does not support it)
            "null_supported": bool(speed_gain <= margin + speed_gain_spread),
            "meta_wins_adaptation_speed": bool(speed_gain > margin + speed_gain_spread),
            "meta_wins_forward_transfer": bool(xfer_gain > margin / max_adapt_steps + xfer_gain_spread),
        }
        return out
